"""Question sets for the Overton update, frozen.

SET_V1: the book's fifteen questions and codings (Chapter 12).

SET_V2: selected 2026-10-30 by the rule in overton_plan.md:
- Pool: opinion questions in the full GSS 1972-2024 file (R3a), asked in
  at least 17 of the 33 waves with polviews (overton_candidates.py,
  overton_scope.py).
- Coding: the book's codings for its fifteen; otherwise the contiguous
  cut that best separates conservatives and liberals (overton_coding.py).
- Ranking: weighted logit(conservative ~ year + cohort + polviews), by the
  polviews coefficient (overton_ranking.py).
- One question per hand-assigned topic (overton_topics.py); for spending
  items, the original wording.
- The top 15.
No trends were computed during selection.

Running this module writes overton_questions.yaml, our own metadata for
the questions in either set (wording and value labels from the gssrdoc
codebook in the CultureWar repo).

Usage: python overton_question_sets.py
"""

import json
from pathlib import Path

import pandas as pd
import yaml

from overton_candidates import GSSRDOC
from overton_coding import parse_labels
from overton_data import CONSERVATIVE_VALUES
from overton_pipeline import FIG_DIR
from overton_topics import topic

SET_V1 = dict(CONSERVATIVE_VALUES)

SET_V2 = {
    "homosex": [1, 2, 3],
    "helppoor": [4, 5],
    "helpnot": [4, 5],
    "sexeduc": [2],
    "helpsick": [3, 4, 5],
    "eqwlth": [4, 5, 6, 7],
    "abany": [2],
    "pillok": [3, 4],
    "helpblk": [4, 5],
    "natarms": [1, 2],
    "racdif1": [2],
    "premarsx": [1, 2, 3],
    "grass": [2],
    "natenvir": [2, 3],
    "cappun": [1],
}

SETS = {"v1": SET_V1, "v2": SET_V2}

METADATA = Path(__file__).resolve().parent / "overton_questions.yaml"


def write_metadata():
    gssrdoc = json.load(open(GSSRDOC))
    ranking = pd.read_csv(FIG_DIR / "candidates_ranking.csv", index_col=0)
    names = sorted(set(SET_V1) | set(SET_V2), key=lambda v: ranking.loc[v, "rank"])
    entries = {}
    for varname in names:
        doc = gssrdoc[varname]
        labels = parse_labels(doc["value_labels"])
        codes = SET_V2.get(varname) or SET_V1[varname]
        row = ranking.loc[varname]
        entries[varname] = dict(
            source="gss",
            description=doc["description"],
            topic=topic(varname),
            question=" ".join(doc["question"].split()),
            value_labels={int(k): v for k, v in labels.items()},
            conservative=codes,
            sets=[name for name, s in SETS.items() if varname in s],
            rank=int(row["rank"]),
            polviews_param=round(float(row["param"]), 3),
            waves=int(row["waves"]),
            first=int(row["first"]),
            last=int(row["last"]),
            in_person_only_since_2022=bool(row["in_person_only"]),
        )
    header = "# Metadata for the Overton question sets. Generated by overton_question_sets.py.\n"
    with open(METADATA, "w") as f:
        f.write(header)
        yaml.safe_dump(entries, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"Wrote {len(entries)} questions to {METADATA}")


if __name__ == "__main__":
    write_metadata()
